"""Turn inline "/表情名" and "[@QQ号]" markers in model replies into QQ segments."""

import re

from astrbot.api.event import AstrMessageEvent, filter
from astrbot.api.message_components import At, Face, Plain
from astrbot.api.star import Context, Star, register

from .qq_faces import QQ_FACE_IDS

# "[@123456]" becomes an @ mention. Only plain QQ numbers are accepted, so the
# model cannot @ everyone. One trailing space is eaten because the aiocqhttp
# adapter already puts a space after every @.
# "/name" follows the MaiBot SnowLuma adapter rule: it is a face only when it
# is not glued to a letter, digit, "_", "/" or ":" before it (keeps URLs and
# "666/赞" as text) and no word character follows it ("/赞说得好" stays text).
# Longer face names are tried first so "/大哭" is not cut short by "/大".
MARKER_PATTERN = re.compile(
    r"\[@(?P<qq>\d{5,12})\] ?"
    r"|(?<![A-Za-z0-9_/:])/(?P<face>"
    + "|".join(
        re.escape(name) for name in sorted(QQ_FACE_IDS, key=len, reverse=True)
    )
    + r")(?!\w)"
)


@register(
    "astrbot_plugin_qq_face_inline",
    "happycola233",
    "把模型回复里的「/表情名」和「[@QQ号]」转换成 QQ 小黄脸和 @",
    "1.1.0",
)
class QQFaceInline(Star):
    def __init__(self, context: Context):
        super().__init__(context)

    @filter.on_decorating_result()
    async def convert_markers(self, event: AstrMessageEvent):
        """Split the text of a model reply into text, face and @ segments.

        Only replies generated by the model on the aiocqhttp platform are
        touched, so plugin command output keeps its literal text. "[@QQ号]"
        becomes an @ in group chats and is removed in private chats, where an
        @ has no meaning.

        Args:
            event: The event whose reply is about to be sent.
        """
        if event.get_platform_name() != "aiocqhttp":
            return
        result = event.get_result()
        if result is None or not result.is_llm_result():
            return
        in_group = bool(event.get_group_id())

        new_chain = []
        for comp in result.chain:
            if not isinstance(comp, Plain) or not MARKER_PATTERN.search(comp.text):
                new_chain.append(comp)
                continue
            cursor = 0
            for match in MARKER_PATTERN.finditer(comp.text):
                if match.start() > cursor:
                    new_chain.append(Plain(comp.text[cursor : match.start()]))
                if match.group("face"):
                    new_chain.append(Face(id=QQ_FACE_IDS[match.group("face")]))
                elif in_group:
                    new_chain.append(At(qq=match.group("qq")))
                cursor = match.end()
            if cursor < len(comp.text):
                new_chain.append(Plain(comp.text[cursor:]))
        result.chain = new_chain
