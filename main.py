"""Turn inline "/表情名" markers in model replies into QQ face segments."""

import re

from astrbot.api.event import AstrMessageEvent, filter
from astrbot.api.message_components import Face, Plain
from astrbot.api.star import Context, Star, register

from .qq_faces import QQ_FACE_IDS

# Same rule as the MaiBot SnowLuma adapter: "/name" is a face only when it is
# not glued to a letter, digit, "_", "/" or ":" before it (keeps URLs and
# "666/赞" as text) and no word character follows it ("/赞说得好" stays text).
# Longer names are tried first so "/大哭" is not cut short by a shorter name.
FACE_PATTERN = re.compile(
    r"(?<![A-Za-z0-9_/:])/("
    + "|".join(
        re.escape(name) for name in sorted(QQ_FACE_IDS, key=len, reverse=True)
    )
    + r")(?!\w)"
)


@register(
    "astrbot_plugin_qq_face_inline",
    "happycola233",
    "把模型回复里的「/表情名」转换成 QQ 小黄脸",
    "1.0.0",
)
class QQFaceInline(Star):
    def __init__(self, context: Context):
        super().__init__(context)

    @filter.on_decorating_result()
    async def convert_faces(self, event: AstrMessageEvent):
        """Split the text of a model reply into text and QQ face segments.

        Only replies generated by the model on the aiocqhttp platform are
        touched, so plugin command output keeps its literal "/" text.

        Args:
            event: The event whose reply is about to be sent.
        """
        if event.get_platform_name() != "aiocqhttp":
            return
        result = event.get_result()
        if result is None or not result.is_llm_result():
            return

        new_chain = []
        for comp in result.chain:
            if not isinstance(comp, Plain) or not FACE_PATTERN.search(comp.text):
                new_chain.append(comp)
                continue
            cursor = 0
            for match in FACE_PATTERN.finditer(comp.text):
                if match.start() > cursor:
                    new_chain.append(Plain(comp.text[cursor : match.start()]))
                new_chain.append(Face(id=QQ_FACE_IDS[match.group(1)]))
                cursor = match.end()
            if cursor < len(comp.text):
                new_chain.append(Plain(comp.text[cursor:]))
        result.chain = new_chain
